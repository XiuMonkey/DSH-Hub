#pragma once

// ------------------------------------------------------------------
// Tooltip.h
// ------------------------------------------------------------------
// 应用统一的「悬浮提示」模块：接管 Qt 原生 QToolTip，换成主题一致的自绘气泡。
//
// 为什么值得单独做一层：
//   * 原生提示框是一块方角纯色底 + 系统默认字体，在自绘圆角窗口里很突兀；
//   * QSS 管不了它 —— QToolTip 是 Qt 内部自己建的顶层 QLabel，`QToolTip {...}`
//     这套选择器只能改底色/文字，圆角、描边、阴影、内外边距一概不生效。
//     （ThemeManager 现在只能把 QPalette::ToolTipBase/ToolTipText 喂给它，形状
//      仍是系统的。）
//
// 接管方式：应用级事件过滤器拦 QEvent::ToolTip。这样做的关键好处是
// **零改动接管**：
//   * 文案的唯一来源仍然是 QWidget::toolTip()，所以既有的 20 余处
//     setToolTip(...) 调用点一行都不用改；
//   * TranslationUi 的「按快照就地换文案」读的也正是 widget->toolTip()
//     （见 src/ui/TranslationUi.cpp），切语言后下一次悬浮就是新语言。
//
// 时序：首次悬浮的延时**由 Qt 给**（实测 QEvent::ToolTip 到达时距鼠标移动约
// 700ms，且从一个有提示的控件移到另一个时 Qt 会自己缩短延时）。所以本模块
// 不再叠加任何自定义延时 —— 加了就是双重等待，手感发黏。
//
// 与主题的关系：本模块的气泡窗口是**常驻单例**（不像各弹窗每次新建），
// 而 ThemeManager::instance().setMode() 只换全局调色板、不会重挂已存在的顶层窗口，所以显示前
// 会检查当前深浅色是否变过，变了就重挂一次样式表。
//
// 与语言/主题的解耦点只有一个：文案在**显示那一刻**现取（widget->toolTip()），
// 颜色在显示那一刻现取（色板 -> QSS）。两者都不需要通知机制。
// ------------------------------------------------------------------

#include <QString>

class QWidget;

namespace Tooltip
{
	// 装应用级事件过滤器。QApplication 构造之后、任意窗口显示之前调一次即可；
	// 重复调用无副作用（内部只装一次）。
	void install();

	// 立刻收掉当前气泡（切主题、切语言、要清场时用）。
	// 尚未创建过气泡时是空操作。
	void hide();

	// 当前是否有气泡正在显示（调试与测试用）
	bool isVisible();

	// 当前气泡的文案；未显示时为空串（调试与测试用）
	QString currentText();

	// 气泡窗口本身，供测试与调试取几何信息；尚未创建过时返回 nullptr。
	// 正常业务代码不需要它 —— 全部交互都由 install() 装的过滤器驱动。
	QWidget* windowForTest();
}
